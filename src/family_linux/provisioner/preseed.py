"""Debian preseed generator for Family Linux.

Generates the Debian Installer (d-i) preseed file and the late-command script that runs inside the
installer after KDE Plasma is installed. Together they make an unattended install of Debian stable
with the parent account, the child accounts, the family groups and sudoers, the Family Linux payload,
and the first-boot unit.

The preseed is read from the ISO (file=/cdrom/preseed.cfg). Its late command runs
/cdrom/family-linux/late-command.sh, which is generated here as well. Every value that reaches the
shell is quoted with shlex.quote.
"""

from __future__ import annotations

import re
import secrets
import shlex
from typing import List, Optional

from family_linux.models import FamilyPolicy
from family_linux.provisioner.sha512crypt import sha512_crypt

# Paths on the ISO (and in the installer, where the CD is mounted at /cdrom).
ISO_PAYLOAD_DIR = "/cdrom/family-linux"
LATE_SCRIPT_NAME = "late-command.sh"
FIRSTBOOT_UNIT = "family-linux-firstboot.service"
WALLPAPER_GLOB = "wallpaper.*"  # the build copies the chosen image to wallpaper.<extension>
SET_WALLPAPER_SCRIPT = "family-linux-set-wallpaper"

# Installed with the system, on top of the KDE Plasma task (see kde-desktop below).
PACKAGES: List[str] = [
    # Security baseline: firewall, confinement, updates, DNS, passwords, network filter
    "ufw",
    "apparmor",
    "apparmor-utils",
    "unattended-upgrades",
    "nftables",
    "systemd-resolved",
    "libpam-pwquality",
    "cracklib-runtime",  # the dictionary pam_pwquality needs; without it every password change fails
    # Networking on the desktop: NetworkManager manages the connection and the DNS filter
    "network-manager",
    # The parent's Family Controls app (Qt, through PyQt6) and the Family Linux CLI
    "python3",
    "python3-yaml",
    "python3-pyqt6",
    # Family Controls runs family-ctl through pkexec; Debian 13 ships it apart from polkit
    "pkexec",
    "libnotify-bin",
    # Applications for children. Installs go through Discover (the Debian app store) and need the
    # parent's password, see security/package_gate.py.
    "firefox-esr",
    "tuxpaint",
    "libreoffice",
    "vlc",
    "kcalc",
    # Discover installs through PackageKit; the PackageKit backend itself ships in plasma-discover.
    # (plasma-discover-backend-packagekit does not exist in Debian 13.)
    "plasma-discover",
    "packagekit",
]

# Commands the late script runs inside the installed system (in-target).
LATE_SHELL_HEADER = """#!/bin/sh
# Family Linux: late command for the Debian installer. Generated by family_linux.provisioner.preseed.
# Runs once, in the installer, after KDE Plasma is installed. Log: /var/log/family-linux-install.log
# on the installed system. Every step is independent, so one failure does not stop the others.
# A failed step is listed in /var/lib/family-linux/install-failures; first boot and verify report it.
T=/target
PAYLOAD=/cdrom/family-linux
exec >> "$T/var/log/family-linux-install.log" 2>&1
echo "== Family Linux late command, $(date)"
mkdir -p "$T/var/lib/family-linux"
: > "$T/var/lib/family-linux/install-failures"
FAILED=0
fail() { FAILED=$((FAILED + 1)); printf 'FAILED: %s\n' "$1"; printf '%s\n' "$1" >> "$T/var/lib/family-linux/install-failures"; }
"""
INSTALL_FAILURES_PATH = "/var/lib/family-linux/install-failures"
INSTALL_STATUS_PATH = "/var/lib/family-linux/install-status"


def _with_failure_check(line: str) -> str:
    """Appends `|| fail <step>` to a command line. Password hashes never reach the failure list."""
    if not line.strip() or line.lstrip().startswith("#"):
        return line
    label = re.sub(r"\$6\$[^' ]*", "<hash>", line)
    return f"{line} || fail {shlex.quote(label)}"


def _quote(value: str) -> str:
    return shlex.quote(value)


class DebianPreseedGenerator:
    """Builds the preseed and the late-command script from a FamilyPolicy."""

    def __init__(self, policy: FamilyPolicy):
        self.policy = policy

    def _hash_password(self, plaintext: Optional[str]) -> str:
        """SHA-512 crypt hash for /etc/shadow. "!" (locked) when there is no password."""
        if not plaintext:
            return "!"
        return sha512_crypt(plaintext, secrets.token_hex(8))

    def generate_preseed(
        self,
        locale: str = "en_US.UTF-8",
        keyboard_layout: str = "us",
        target_disk: Optional[str] = None,
        hostname: str = "family-linux",
        unattended_disk: bool = False,
    ) -> str:
        """Returns the d-i preseed file (debconf lines).

        By default the installer stops at "Write the changes to disks?" so a person confirms the erase.
        unattended_disk=True answers that too; only the automated build (no one at the screen) uses it.
        """
        parent = self.policy.parent
        timezone = self.policy.timezone or "UTC"
        lines = [
            "# Family Linux: Debian Installer preseed. Generated by family_linux.provisioner.preseed.",
            "# Contains the parent password hash only (no plain-text passwords). Do not edit by hand.",
            "",
            "# Language, keyboard, network and time zone",
            f"d-i debian-installer/locale string {locale}",
            f"d-i keyboard-configuration/xkb-keymap select {keyboard_layout}",
            "d-i netcfg/choose_interface select auto",
            f"d-i netcfg/get_hostname string {hostname}",
            "d-i netcfg/get_domain string local",
            "d-i netcfg/wireless_wep string",
            "d-i mirror/country string manual",
            "d-i mirror/http/hostname string deb.debian.org",
            "d-i mirror/http/directory string /debian",
            "d-i mirror/http/proxy string",
            "d-i clock-setup/utc boolean true",
            f"d-i time/zone string {timezone}",
            "d-i clock-setup/ntp boolean true",
            "",
            "# Accounts: no root login; the parent is the only administrator (sudo group).",
            "# Child accounts are created by the late command, after the system is installed.",
            "d-i passwd/root-login boolean false",
            "d-i passwd/make-user boolean true",
            f"d-i passwd/user-fullname string {parent.full_name}",
            f"d-i passwd/username string {parent.username}",
            f"d-i passwd/user-password-crypted password {self._hash_password(parent.password)}",
            "d-i passwd/user-default-groups string sudo adm",
            "",
            "# Disk: the disk chosen in the installer, otherwise the first disk the installer finds",
            "d-i partman-auto/method string regular",
        ]
        if target_disk:
            lines.append(f"d-i partman-auto/disk string {target_disk}")
        else:
            lines.append('d-i partman/early_command string debconf-set partman-auto/disk "$(list-devices disk | head -n1)"')
        lines.append("d-i partman-auto/choose_recipe select atomic")
        if unattended_disk:
            lines += [
                "# Unattended build: the disk is erased without a confirmation screen",
                "d-i partman-partitioning/confirm_write_new_label boolean true",
                "d-i partman/choose_partition select finish",
                "d-i partman/confirm boolean true",
                "d-i partman/confirm_nooverwrite boolean true",
                "d-i partman-md/device_remove_md boolean true",
                "d-i partman-lvm/device_remove_lvm boolean true",
                "d-i partman-lvm/confirm boolean true",
                "d-i partman-lvm/confirm_nooverwrite boolean true",
            ]
        else:
            lines.append("# The installer asks before it writes to the disk (no answer is given here)")
        lines += [
            "",
            "# Debian repositories: main, contrib and non-free-firmware, with security and updates",
            "d-i apt-setup/use_mirror boolean true",
            "d-i apt-setup/contrib boolean true",
            "d-i apt-setup/non-free-firmware boolean true",
            "d-i apt-setup/non-free boolean false",
            "d-i apt-setup/services-select multiselect security, updates",
            "d-i apt-setup/disable-cdrom-entries boolean true",
            "",
            "# Desktop: KDE Plasma, then the packages the Family Linux baseline needs",
            "tasksel tasksel/first multiselect kde-desktop",
            "d-i pkgsel/include string " + " ".join(PACKAGES),
            "d-i pkgsel/upgrade select none",
            "d-i pkgsel/update-policy select none",
            "popularity-contest popularity-contest/participate boolean false",
            "",
            "# Boot: UEFI, with the removable-media path so the disk still boots after it is moved",
            "d-i grub-installer/only_debian boolean true",
            "d-i grub-installer/with_other_os boolean false",
            "d-i grub-installer/bootdev string default",
            "d-i grub-installer/force-efi-extra-removable boolean true",
            "",
            "# Family accounts, policy, payload and first-boot unit (see the late command)",
            f"d-i preseed/late_command string sh {ISO_PAYLOAD_DIR}/{LATE_SCRIPT_NAME}",
            "d-i finish-install/reboot_in_progress note",
            "",
        ]
        return "\n".join(lines)

    def generate_late_script(self, poweroff_after_firstboot: bool = False) -> str:
        """Returns the shell script that the installer runs after the base system is installed."""
        parent = self.policy.parent
        out: List[str] = [LATE_SHELL_HEADER]

        out.append("# 1. Family groups, the parent's administrator rights and the children's sudo ban")
        out.append("in-target groupadd -f family-parent")
        out.append("in-target groupadd -f family-children")
        out.append(f"in-target usermod -aG sudo,adm,family-parent {_quote(parent.username)}")
        out.append(f"in-target chmod 700 {_quote('/home/' + parent.username)}")
        out.append('printf "%s\\n" "# Family Linux security policy" '
                   f"{_quote(parent.username + ' ALL=(ALL:ALL) ALL')} "
                   f"{_quote('%family-children ALL=(ALL:ALL) !ALL')} > $T/etc/sudoers.d/family-linux-admin")
        out.append("chmod 0440 $T/etc/sudoers.d/family-linux-admin")
        out.append("")

        out.append("# 2. Child accounts: standard users, nologin shell, no sudo, password hash only")
        for child in self.policy.children:
            out.append(
                "in-target useradd -m "
                f"-s {_quote(child.shell)} -c {_quote(child.full_name)} -g family-children "
                f"-p {_quote(self._hash_password(child.password))} {_quote(child.username)}"
            )
        out.append("")

        # 3. Firewall: applied by the first boot. ufw cannot run in the installer's chroot (all three
        #    commands failed there, seen in the appliance build), and the system has no network
        #    services listening before its first boot.

        out.append("# 4. Family Linux payload, policy (no passwords) and the first-boot unit")
        out.append("mkdir -p $T/opt $T/etc/family-linux $T/etc/systemd/system $T/usr/local/sbin $T/usr/local/bin")
        out.append("mkdir -p $T/usr/share/applications $T/usr/share/polkit-1/actions $T/usr/lib/python3/dist-packages")
        out.append("cp -a $PAYLOAD $T/opt/")
        out.append("install -m 644 $PAYLOAD/policy.yaml $T/etc/family-linux/policy.yaml")
        out.append(f"install -m 644 $PAYLOAD/{FIRSTBOOT_UNIT} $T/etc/systemd/system/{FIRSTBOOT_UNIT}")
        out.append(f"in-target systemctl enable {FIRSTBOOT_UNIT}")
        out.append("printf '%s\\n' /opt/family-linux/src > $T/usr/lib/python3/dist-packages/family-linux.pth")
        out.append("install -m 755 $PAYLOAD/family-ctl $T/usr/local/sbin/family-ctl")
        out.append("install -m 755 $PAYLOAD/family-linux-parent $T/usr/local/bin/family-linux-parent")
        out.append("install -m 644 $PAYLOAD/org.familylinux.Parent.desktop $T/usr/share/applications/org.familylinux.Parent.desktop")
        out.append("install -m 644 $PAYLOAD/org.familylinux.manage.policy $T/usr/share/polkit-1/actions/org.familylinux.manage.policy")
        out.append("")

        out.append("# 5. Wallpaper: the image, and a per-account step at the first Plasma login (see the script)")
        out.append("mkdir -p $T/usr/share/backgrounds/family-linux $T/etc/xdg/autostart $T/usr/libexec/family-linux")
        out.append(f'for image in $PAYLOAD/{WALLPAPER_GLOB}; do [ -f "$image" ] && install -m 644 "$image" $T/usr/share/backgrounds/family-linux/; done')
        out.append(f"install -m 755 $PAYLOAD/{SET_WALLPAPER_SCRIPT} $T/usr/libexec/family-linux/{SET_WALLPAPER_SCRIPT}")
        out.append(f"install -m 644 $PAYLOAD/family-linux-wallpaper.desktop $T/etc/xdg/autostart/family-linux-wallpaper.desktop")
        out.append("")

        out.append("# 6. Networking: NetworkManager manages every connection and uses systemd-resolved for DNS,")
        out.append("# so the family DNS filter applies. ifupdown keeps only the loopback interface.")
        out.append("mkdir -p $T/etc/NetworkManager/conf.d")
        out.append("printf '[ifupdown]\\nmanaged=true\\n' > $T/etc/NetworkManager/conf.d/family-linux-network.conf")
        out.append("printf '[main]\\ndns=systemd-resolved\\n' > $T/etc/NetworkManager/conf.d/family-linux-dns.conf")
        out.append("printf 'auto lo\\niface lo inet loopback\\n' > $T/etc/network/interfaces")
        out.append("in-target systemctl enable systemd-resolved.service")
        out.append("in-target ln -sf /run/systemd/resolve/stub-resolv.conf /etc/resolv.conf")
        out.append("")

        if poweroff_after_firstboot:
            out.append("# Appliance build: the first boot powers off once the policy is applied (clean export)")
            out.append(": > $T/etc/family-linux/poweroff-after-firstboot")
            out.append("")

        out.append("# 7. Security updates run every day, with no prompts")
        out.append("mkdir -p $T/etc/apt/apt.conf.d")
        out.append("printf '%s\\n' 'APT::Periodic::Update-Package-Lists \"1\";' "
                   "'APT::Periodic::Unattended-Upgrade \"1\";' > $T/etc/apt/apt.conf.d/20auto-upgrades")
        out.append("in-target systemctl enable unattended-upgrades.service")
        out.append("")
        steps = [_with_failure_check(line) for line in out[1:]]
        ending = [
            'echo "failed=$FAILED" > "$T' + INSTALL_STATUS_PATH + '"',
            'echo "== Family Linux late command finished ($FAILED failed)"',
            # The installer carries on either way; first boot and verify report the failures.
            "exit 0",
        ]
        return "\n".join([out[0], *steps, *ending]) + "\n"
